package com.coke.nestspace.container

import android.app.Activity
import android.app.Instrumentation
import android.content.Context
import android.content.Intent
import android.os.Bundle
import android.os.IBinder
import android.util.Log

/**
 * Instrumentation handed to target Activities through Activity.attach.
 *
 * Activity.startActivityForResult calls
 * `mInstrumentation.execStartActivity(this, ...)`; that method is public in
 * AOSP but hidden from the SDK stubs. We declare the exact AOSP signatures
 * without `override` (the hidden-API exemption is installed before attach), so
 * ART dispatches to it at runtime.
 *
 * In-package intents are turned into another StageAActivity host backed by the
 * same ContainerSession. External intents are launched through the current host,
 * which has a real token and the host package/UID.
 *
 * Runtime permission requests are generated by the framework as an Intent to
 * the permission controller. The controller cannot grant permissions to a
 * package that is not installed, so the request is answered by
 * ContainerPermissions instead (real host dialog where possible).
 */
class ContainerInstrumentation(
    private val sessionProvider: () -> ContainerSession
) : Instrumentation() {

    @Suppress("UNUSED_PARAMETER")
    fun execStartActivity(
        who: Context?,
        contextThread: IBinder?,
        token: IBinder?,
        target: Activity?,
        intent: Intent?,
        requestCode: Int,
        options: Bundle?
    ): ActivityResult? {
        if (intent == null) return null
        val session = sessionProvider()
        val host = target?.let { session.hostFor(it) } ?: session.navigator
        if (host == null) {
            Log.w(TAG, "no host for startActivity: ${intent.component}")
            return null
        }
        if (handlePermissionRequest(session, host, target, intent, requestCode)) return null
        if (session.startTargetActivity(host, intent, requestCode)) return null
        Log.w(
            TAG,
            "startActivity falls back to host: component=${intent.component} " +
                "action=${intent.action} package=${intent.`package`}"
        )
        if (session.startExternalActivity(host, intent, requestCode)) return null
        return null
    }

    /**
     * String-target overload used by Activity.requestPermissions. The
     * framework passes the permission-controller intent here with no Activity
     * target, so resolve the target from the host.
     */
    @Suppress("UNUSED_PARAMETER")
    fun execStartActivity(
        who: Context?,
        contextThread: IBinder?,
        token: IBinder?,
        target: String?,
        intent: Intent?,
        requestCode: Int,
        options: Bundle?
    ): ActivityResult? {
        val session = sessionProvider()
        val host = session.navigator
        if (intent == null || host == null) {
            return execStartActivity(
                who,
                contextThread,
                token,
                null as Activity?,
                intent,
                requestCode,
                options
            )
        }
        if (handlePermissionRequest(
                session,
                host,
                null,
                intent,
                requestCode
            )
        ) {
            return null
        }
        return execStartActivity(
            who,
            contextThread,
            token,
            null as Activity?,
            intent,
            requestCode,
            options
        )
    }

    private fun handlePermissionRequest(
        session: ContainerSession,
        host: StageAActivity,
        target: Activity?,
        intent: Intent,
        requestCode: Int
    ): Boolean {
        if (!isPermissionRequest(intent)) return false
        val permissions = intent.getStringArrayExtra(EXTRA_REQUEST_PERMISSIONS_NAMES)
        if (permissions.isNullOrEmpty()) return false
        val targetActivity = target
            ?: session.navigator?.currentTargetActivity()
            ?: session.activeTarget()
        Log.d(
            TAG,
            "permission request code=$requestCode permissions=${permissions.joinToString()}"
        )
        session.context.permissions.request(
            hostActivity = host,
            targetActivity = targetActivity,
            permissions = permissions,
            targetRequestCode = requestCode
        )
        return true
    }

    private fun isPermissionRequest(intent: Intent): Boolean {
        if (intent.action == ACTION_REQUEST_PERMISSIONS) return true
        val className = intent.component?.className ?: return false
        return className.contains("GrantPermissionsActivity") ||
            className.contains("permissioncontroller", ignoreCase = true)
    }

    private fun ContainerSession.activeTarget(): Activity? =
        navigator?.currentTargetActivity()

    private companion object {
        const val TAG = "ContainerInstr"
        const val ACTION_REQUEST_PERMISSIONS =
            "android.content.pm.action.REQUEST_PERMISSIONS"
        const val EXTRA_REQUEST_PERMISSIONS_NAMES =
            "android.content.pm.extra.REQUEST_PERMISSIONS_NAMES"
    }
}
